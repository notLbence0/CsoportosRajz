import turtle
turtle.speed(0)

turtle.color("lightblue")
turtle.penup()
turtle.goto(-300,300)
turtle.pendown()
turtle.fillcolor("lightblue")
turtle.begin_fill()
turtle.forward(300)
turtle.right(90)
turtle.forward(600)
turtle.right(90)
turtle.forward(300)
turtle.right(90)
turtle.forward(600)
turtle.end_fill()

turtle.done()
